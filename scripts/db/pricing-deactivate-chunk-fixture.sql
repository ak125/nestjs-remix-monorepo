-- Assertions : chaque échec lève une exception (psql ON_ERROR_STOP arrête le test).
CREATE TABLE t_ok (n serial, label text);
GRANT ALL ON t_ok TO PUBLIC;
GRANT ALL ON SEQUENCE t_ok_n_seq TO PUBLIC;
CREATE FUNCTION eq(label text, actual anyelement, expected anyelement) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  IF actual IS DISTINCT FROM expected THEN
    RAISE EXCEPTION 'ÉCHEC % : obtenu %, attendu %', label, actual, expected;
  END IF;
  INSERT INTO t_ok(label) VALUES (label);
END $$;
-- L'erreur attendue est levée dans un sous-bloc : ses écritures sont annulées
-- avec elle, comme l'appel RPC entier côté backend.
CREATE FUNCTION expect_error(label text, q text, pattern text) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  BEGIN
    EXECUTE q;
  EXCEPTION WHEN OTHERS THEN
    IF SQLERRM NOT LIKE pattern THEN
      RAISE EXCEPTION 'ÉCHEC % : erreur inattendue %', label, SQLERRM;
    END IF;
    INSERT INTO t_ok(label) VALUES (label);
    RETURN;
  END;
  RAISE EXCEPTION 'ÉCHEC % : aucune erreur levée', label;
END $$;
