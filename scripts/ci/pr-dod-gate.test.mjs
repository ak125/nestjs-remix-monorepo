const HEAD = "4d473f6a2a80c4eaa3843974a179a9dece4b94f0";
const OLD_HEAD = "0fbf05e8bdaa36c2f1c0b8f7c2b4e1d9a3f6e5c7";
const BASE = "6ab7854c2adf15e3e588f8a73e4f9085ecaeee5d";
const PR = { headSha: HEAD, number: 7, repo: "o/r", mergeBase: BASE, files: ["docs/x.md"], comments: [], reviews: [] };
// State that satisfies DoD2 (ADR-120): an assignee and a record on the head.
const OWNED = { assignees: ["owner"], pr: PR };
const CLEAN = { problems: [], unverified: [] };
const checks = ({ problems, unverified }) => ({ problems, unverified });

function record({ level = "A", head = HEAD, base = BASE, procedure = "auto-review, par la session auteure", limites = "aucune revue indépendante" } = {}) {
  return [
    `  - [x] Revue niveau ${level} — tête ${head}, base ${base}`,
    `        procédure : ${procedure}`,
    "        périmètre : docs/x.md, sans exclusion",
    "        constats : 0 corrigé, 0 réfuté, 0 reporté",
    "        preuves : lint → 0 violation ; reprises : aucune",
    `        limites : ${limites}`,
  ].join("\n");
}

function fullBody({ na7 = true, review = record() } = {}) {
  return [
    "## Definition of Done — auto-évaluation",
    "- [x] **DoD1** Tests verts",
    "- [x] **DoD2** Ownership",
    review,
    "- [x] **DoD3** Rollback: revert PR",
    "- [x] **DoD4** Observabilité",
    "- [x] **DoD5** Drift zéro",
    "- [x] **DoD6** Docs",
    na7 ? "- [ ] **DoD7** Monitoring : N/A ce PR" : "- [x] **DoD7** Monitoring",
    "- [x] **DoD8** No TODO",
    "- [x] **DoD9** No silent skip",
  ].join("\n");
}

describe("evaluateDoD — checklist mode", () => {
  test("passes when all 9 checked or N/A", () => {
    const r = evaluateDoD(fullBody(), [], 1, OWNED);
    assert.equal(r.mode, "checklist");
    assert.equal(r.pass, true);
  });

  test("N/A line counts as satisfied", () => {
    const r = evaluateDoD(fullBody({ na7: true }), [], 1, OWNED);
    assert.equal(r.pass, true);
  });

  test("fails when a DoD line is missing", () => {
    const body = fullBody().split("\n").filter((l) => !l.includes("DoD5")).join("\n");
    const r = evaluateDoD(body, [], 1, OWNED);
    assert.equal(r.pass, false);
    assert.ok(r.reasons.some((x) => x.includes("DoD5: missing")));
  });

  test("fails when a DoD line is unchecked and not N/A", () => {
    const body = fullBody({ na7: false }).replace(
      "- [x] **DoD3** Rollback: revert PR",
      "- [ ] **DoD3** Rollback",
    );
    const r = evaluateDoD(body, [], 1, OWNED);
    assert.equal(r.pass, false);
    assert.ok(r.reasons.some((x) => x.includes("DoD3: present but unchecked")));
  });

  test("empty body fails with all 9 missing", () => {
    const r = evaluateDoD("", [], 0);
    assert.equal(r.pass, false);
    assert.equal(r.reasons.length, DOD_IDS.length);
    assert.deepEqual(r.onProof, DOD2_ON_PROOF);
  });

  test("the evidence list names carry-over and the accord's account", () => {
    assert.ok(DOD2_ON_PROOF.some((x) => x.startsWith("carry-over (D4)")));
    assert.ok(DOD2_ON_PROOF.some((x) => x.startsWith("level C accord: the counted account is the domain owner")));
    assert.ok(DOD2_ON_PROOF.some((x) => x.startsWith("projections at level A were regenerated by their script")));
  });

  test("DoD1 word boundary does not match DoD10-style noise", () => {
    // A line mentioning 'DoD10' must NOT satisfy DoD1.
    const body = fullBody().replace("- [x] **DoD1** Tests verts", "- [x] DoD10 unrelated");
    const r = evaluateDoD(body, [], 1, OWNED);
    assert.equal(r.pass, false);
    assert.ok(r.reasons.some((x) => x.includes("DoD1: missing")));
  });
});

describe("evaluateDoD — checklist lines only", () => {
  test("accepts the vault template format and other list markers", () => {
    const body = fullBody()
      .replace("- [x] **DoD1** Tests verts", "- [x] DoD1 — Tests verts: CI green")
      .replace("- [x] **DoD8** No TODO", "* [X] DoD8 — No TODO unresolved: 0");
    assert.equal(evaluateDoD(body, [], 1, OWNED).pass, true);
  });

  test("a prose mention before the checklist line does not shadow it", () => {
    const body = "Surveillance : voir DoD7 plus bas.\n" + fullBody({ na7: false });
    assert.equal(evaluateDoD(body, [], 1, OWNED).pass, true);
  });

  test("a list item without a box counts only through N/A", () => {
    const na = fullBody().replace("- [x] **DoD4** Observabilité", "- DoD4 — N/A : aucun code runtime");
    assert.equal(evaluateDoD(na, [], 1, OWNED).pass, true);
    const bare = fullBody().replace("- [x] **DoD4** Observabilité", "- DoD4 — logger ajouté");
    const r = evaluateDoD(bare, [], 1, OWNED);
    assert.ok(r.reasons.some((x) => x.includes("DoD4: present but unchecked")));
  });

  test("the vault template pasted unchanged satisfies nothing", () => {
    const template = [
      "- [ ] DoD1 — Tests verts: CI green, no flaky, no .only/.skip added",
      "- [ ] DoD2 — Ownership: assignee + revue niveau <A|B|C> sur la tête <sha40> (enregistrement : <lien>)",
      "- [ ] DoD3 — Rollback: <plan link>, reversibility=<instant/staged/forward-only>",
      "- [ ] DoD4 — Observabilité: <log/metric/event log added or N/A>",
      "- [ ] DoD5 — Drift zéro: registry-fresh green, migrations atomic",
      '- [ ] DoD6 — Docs: <files updated or "no doc needed">',
      "- [ ] DoD7 — Monitoring: watcher=@<user>, window=T+<duration>, abort=<criteria>",
      "- [ ] DoD8 — No TODO unresolved: <count, all linked>",
      "- [ ] DoD9 — No silent skip: confirmed",
    ].join("\n");
    const r = evaluateDoD(template, [], 0, { assignees: [] });
    assert.deepEqual(r.reasons.map((x) => x.slice(0, 4)), DOD_IDS);
  });

  test("an N/A after a placeholder counts, one split by a placeholder does not", () => {
    const after = fullBody().replace("- [x] **DoD4** Observabilité", "- [ ] **DoD4** Observabilité: <détail> N/A");
    assert.equal(evaluateDoD(after, [], 1, OWNED).pass, true);
    const split = fullBody().replace("- [x] **DoD4** Observabilité", "- [ ] **DoD4** Observabilité: N/<x>A");
    const r = evaluateDoD(split, [], 1, OWNED);
    assert.ok(r.reasons.some((x) => x.startsWith("DoD4: present but unchecked")));
  });

  test("an unboxed bullet citing an id does not shadow its boxed line", () => {
    const body = ["Constat :", "  - DoD5 non coché ;", "  - DoD7 sans surveillant ;", "", fullBody()].join("\n");
    assert.equal(evaluateDoD(body, [], 1, OWNED).pass, true);
  });

  test("boxed lines that disagree fail instead of picking one", () => {
    const body = fullBody().concat("\n- [ ] **DoD5** Drift zéro");
    const r = evaluateDoD(body, [], 1, OWNED);
    assert.equal(r.pass, false);
    assert.ok(r.reasons.some((x) => x.startsWith("DoD5: 2 checklist lines disagree")));
  });

  test("a prose N/A is not a checklist line", () => {
    const body = fullBody()
      .split("\n")
      .filter((l) => !l.includes("**DoD4**"))
      .concat("DoD4 N/A, rien de runtime.")
      .join("\n");
    const r = evaluateDoD(body, [], 1, OWNED);
    assert.equal(r.pass, false);
    assert.ok(r.reasons.some((x) => x.includes("DoD4: missing")));
  });
});

describe("evaluateDoD — DoD2 is an ADR-120 review record", () => {
  const dod2 = (r) => r.reasons.concat(r.advisory).find((x) => x.startsWith("DoD2:")) ?? "";

  test("an assignee and a record on the head satisfy DoD2, with no approval", () => {
    const r = evaluateDoD(fullBody(), [], 0, OWNED);
    assert.equal(r.pass, true);
    assert.equal(dod2(r), "");
  });

  test("approvals do not replace the record", () => {
    const r = evaluateDoD(fullBody({ review: "" }), [], 3, OWNED);
    assert.ok(dod2(r).includes("no review record"));
    assert.ok(dod2(r).includes("box ticked without that evidence"));
  });

  test("a record without assignee fails", () => {
    const r = evaluateDoD(fullBody(), [], 1, { assignees: [], pr: PR });
    assert.deepEqual(r.reasons.map((x) => x.slice(0, 5)), ["DoD2:"]);
    assert.ok(dod2(r).includes("no assignee"));
  });

  test("unknown assignees fail instead of passing", () => {
    const r = evaluateDoD(fullBody(), [], 1, { pr: PR });
    assert.ok(r.reasons.some((x) => x.includes("unverified: assignees unknown")));
  });

  test("N/A does not exempt DoD2", () => {
    const body = fullBody({ review: "" }).replace("- [x] **DoD2** Ownership", "- [ ] **DoD2** Ownership : N/A");
    assert.equal(evaluateDoD(body, [], 0, OWNED).pass, false);
  });

  test("unreadable data is reported unverified, never passed", () => {
    const r = evaluateDoD(fullBody(), [], 0, { assignees: ["owner"] });
    assert.equal(r.pass, false);
    for (const part of ["unverified: head SHA unknown", "unverified: merge-base unknown", "unverified: changed files unknown"]) {
      assert.ok(dod2(r).includes(part), part);
    }
  });
});

describe("evaluateReviewRecord — record bound to the head (D2, D4)", () => {
  test("a record naming another head is stale", () => {
    const { problems } = evaluateReviewRecord(record({ head: OLD_HEAD }), PR);
    assert.ok(problems.some((x) => x.startsWith(`no record names the head ${HEAD}`) && x.includes(OLD_HEAD)));
  });

  test("the stale heads are listed up to five", () => {
    const heads = Array.from({ length: 8 }, (_, i) => `${i}`.repeat(40));
    const { problems } = evaluateReviewRecord(heads.map((head) => record({ head })).join("\n\n"), PR);
    const stale = problems.find((x) => x.startsWith(`no record names the head ${HEAD}`));
    assert.ok(stale.includes(`\`${heads[4]}\`, … (8)`) && !stale.includes(heads[5]), stale);
  });

  test("a short SHA does not name the head, and the message says so", () => {
    const { problems } = evaluateReviewRecord(record({ head: HEAD.slice(0, 9) }), PR);
    assert.deepEqual(problems, [
      `record names ${HEAD.slice(0, 9)}, an abbreviation of the head: the record names the 40-character SHA ${HEAD}`,
    ]);
  });

  test("the base must be the merge-base", () => {
    const { problems } = evaluateReviewRecord(record({ base: OLD_HEAD }), PR);
    assert.ok(problems.some((x) => x.includes(`base ${OLD_HEAD} is not the merge-base ${BASE}`)));
  });

  test("every field is required; a placeholder is not a value", () => {
    const body = record({ limites: "<non couvert>" }).split("\n").filter((l) => !l.includes("périmètre")).join("\n");
    const { problems } = evaluateReviewRecord(body, PR);
    assert.ok(problems.some((x) => x.endsWith("field(s) missing or placeholder: périmètre, limites")));
  });

  test("the procedure names who ran it", () => {
    const { problems } = evaluateReviewRecord(record({ procedure: "auto-review" }), PR);
    assert.ok(problems.some((x) => x.includes("procédure does not name who ran it")));
  });

  test("the rule template pasted unchanged is not a record", () => {
    assert.deepEqual(parseReviewRecords("- [x] Revue niveau <A|B|C> — tête <sha40>, base <sha40>"), []);
  });

  test("the DoD2 line points to the record but is not one, and its SHA must be the head", () => {
    const line = `- [x] DoD2 — Ownership: assignee + revue niveau A sur la tête ${OLD_HEAD} (enregistrement : ci-dessous)`;
    assert.deepEqual(parseReviewRecords(line), []);
    const { problems } = evaluateReviewRecord(`${line}\n${record()}`, PR);
    assert.deepEqual(problems, [`the DoD2 line names ${OLD_HEAD}, the head is ${HEAD}`]);
    const short = evaluateReviewRecord(`${line.replace(OLD_HEAD, HEAD.slice(0, 9))}\n${record()}`, PR);
    assert.deepEqual(short.problems, [
      `the DoD2 line names ${HEAD.slice(0, 9)}, an abbreviation of the head: name the 40-character SHA ${HEAD}`,
    ]);
  });

  test("a template placeholder is not a value, in any field", () => {
    const procedure = "<auto-review | revue indépendante | revue humaine>, par <session, agent ou compte>";
    const { problems } = evaluateReviewRecord(record({ procedure, limites: "aucune ; suivi : <lien>" }), PR);
    assert.ok(problems.some((x) => x.endsWith("field(s) missing or placeholder: procédure, limites")));
    const partial = evaluateReviewRecord(record({ procedure: "auto-review, par <session, agent ou compte>" }), PR);
    assert.ok(partial.problems.some((x) => x.endsWith("field(s) missing or placeholder: procédure")));
    const inCode = evaluateReviewRecord(record({ limites: "le type `Map<string, number>` n'est pas testé" }), PR);
    assert.deepEqual(checks(inCode), CLEAN);
    const constats = "constats : `<n>` corrigés (commit, test), `<n>` réfutés (preuve), `<n>` reportés (motif, suivi)";
    const template = evaluateReviewRecord(record().replace(/constats : .*/, constats), PR);
    assert.ok(template.problems.some((x) => x.endsWith("field(s) missing or placeholder: constats")));
    const command = evaluateReviewRecord(record({ limites: "`git show <sha>` non relancé" }), PR);
    assert.deepEqual(checks(command), CLEAN);
    for (const limites of ["`<non couvert>`", "`<lien>` ;", "** `<sha40>` **"]) {
      const { problems } = evaluateReviewRecord(record({ limites }), PR);
      assert.ok(problems.some((x) => x.endsWith("field(s) missing or placeholder: limites")), limites);
    }
  });

  test("« par » is a word, not a syllable", () => {
    const { problems } = evaluateReviewRecord(record({ procedure: "auto-review préparée hier" }), PR);
    assert.ok(problems.some((x) => x.includes("procédure does not name who ran it")));
  });

  test("a decomposed (NFD) record reads like a composed one", () => {
    const body = record().normalize("NFD");
    assert.notEqual(body, record());
    assert.deepEqual(checks(evaluateReviewRecord(body, PR)), CLEAN);
  });

  test("a long run of spaces after a label is read in linear time", () => {
    const line = `- [x] Revue niveau A — tête${" ".repeat(60000)}x`;
    const started = process.hrtime.bigint();
    parseReviewRecords(line);
    evaluateReviewRecord(`- [x] DoD2 — tête${" ".repeat(60000)}x`, PR);
    assert.ok(Number(process.hrtime.bigint() - started) / 1e6 < 500);
  });

  test("many anchors are read in one pass, each field in its own record", () => {
    const anchors = Array.from({ length: 20000 }, () => `- [x] Revue niveau A — tête ${OLD_HEAD}, base ${BASE}`).join("\n");
    const started = process.hrtime.bigint();
    const records = parseReviewRecords(`${anchors}\n${record()}`);
    assert.ok(Number(process.hrtime.bigint() - started) / 1e6 < 500);
    assert.equal(records.length, 20001);
    assert.deepEqual(records[19999].fields, {});
    assert.equal(records[20000].fields.procedure, "auto-review, par la session auteure");
  });

  test("a field that cites « revue niveau X » stays in its record", () => {
    const procedure = "revue indépendante, par un sous-agent (la revue niveau A précédente est remplacée)";
    const body = record({ level: "B", procedure }).replace(
      "0 corrigé, 0 réfuté, 0 reporté",
      "12 constats de la revue niveau B de 54e0806 traités : 12 corrigés, 0 réfuté, 0 reporté",
    );
    const records = parseReviewRecords(body);
    assert.equal(records.length, 1);
    assert.equal(records[0].fields.procedure, procedure);
    assert.deepEqual(checks(evaluateReviewRecord(body, { ...PR, files: ["scripts/ci/x.mjs"] })), CLEAN);
  });

  test("labels in bold and fields as list items are read", () => {
    const body = record().replace("procédure :", "- **Procédure** :").replace("limites :", "- limites :");
    assert.deepEqual(checks(evaluateReviewRecord(body, PR)), CLEAN);
  });
});

describe("evaluateReviewRecord — level (D3)", () => {
  test("level A with code in the diff needs level B", () => {
    const { problems } = evaluateReviewRecord(record(), { ...PR, files: ["docs/x.md", "scripts/ci/x.mjs"] });
    assert.ok(problems.some((x) => x.includes("level A declared but the diff changes code (`scripts/ci/x.mjs`)")));
  });

  test("a renamed file counts under its previous path too", () => {
    // The workflow lists `previous_filename`: moving a workflow out of `.github/workflows/` is a change to code.
    const { problems } = evaluateReviewRecord(record(), { ...PR, files: ["docs/guard.md", ".github/workflows/guard.yml"] });
    assert.ok(problems.some((x) => x.includes("level A declared but the diff changes code (`.github/workflows/guard.yml`)")));
  });

  test("level A with files neither prose, audit evidence or projection nor code is left to the evidence", () => {
    for (const file of [
      "config/x.yaml",
      "requirements.txt",
      "docs/x.mdx",
      // Guard inputs under audit/: ratchet baselines, overlays, manifests of a fail-closed guard.
      "audit/baselines/revoked-secrets-baseline.json",
      "audit/impeccable/baseline.json",
      "audit/dependencies/family-overlay.yaml",
      "audit/massdoc-tecdoc-preservation-manifest-2026-03.json",
      // Dated snapshots beside them are classified on evidence too.
      "audit/2026-07-19-x.json",
      // Markdown parsed by code: agent frontmatter, canon mirrors.
      ".claude/agents/x.md",
      "agents/.claude/agents/x.md",
      ".claude/canon-mirrors/rules-x.md",
    ]) {
      const { problems, unverified } = evaluateReviewRecord(record(), { ...PR, files: [file] });
      assert.deepEqual(problems, [], file);
      assert.ok(
        unverified.some((x) => x.includes("neither prose, audit evidence or projection nor code") && x.includes(`\`${file}\``)),
        file,
      );
    }
  });

  test("a file name is one line in the report", () => {
    const { unverified } = evaluateReviewRecord(record(), { ...PR, files: ["config/a\nb `c`.yaml"] });
    assert.ok(unverified.some((x) => x.includes("(`config/a b 'c'.yaml`)")), unverified.join("\n"));
  });

  test("audit evidence and projections regenerated by their script stay at level A", () => {
    const files = [
      "docs/x.md",
      "audit/module-boundaries.json",
      "audit/db-usage-map.json",
      "audit/registry/canonical.json",
      "audit/cleanup/candidates.json",
      "audit/content/r1/x.yaml",
      ".claude/knowledge/REPO_MAP.md",
      // Agent instructions stay prose (a ratification choice of the owner).
      "CLAUDE.md",
      ".claude/rules/x.md",
      ".claude/skills/x/SKILL.md",
    ];
    assert.deepEqual(checks(evaluateReviewRecord(record(), { ...PR, files })), CLEAN);
    const script = evaluateReviewRecord(record(), { ...PR, files: ["audit/registry/build.mjs"] });
    assert.ok(script.problems.some((x) => x.includes("level A declared but the diff changes code")));
  });

  test("a file list at the API cap leaves the level unverified", () => {
    const files = Array.from({ length: 3000 }, (_, i) => `docs/${i}.md`);
    const { unverified } = evaluateReviewRecord(record(), { ...PR, files });
    assert.ok(unverified.some((x) => x.startsWith("changed files listed up to the API cap (3000)")));
  });

  test("level B requires an independent review", () => {
    const files = { ...PR, files: ["scripts/ci/x.mjs"] };
    const self = evaluateReviewRecord(record({ level: "B" }), files);
    assert.ok(self.problems.some((x) => x.includes("level B requires an independent or human review")));
    const independent = evaluateReviewRecord(record({ level: "B", procedure: "revue indépendante, par un sous-agent sans contexte" }), files);
    assert.deepEqual(checks(independent), CLEAN);
  });

  test("a human review counts at level B, a negated review does not", () => {
    const files = { ...PR, files: ["scripts/ci/x.mjs"] };
    const human = evaluateReviewRecord(record({ level: "B", procedure: "revue humaine, par un relecteur" }), files);
    assert.deepEqual(checks(human), CLEAN);
    for (const procedure of [
      "**revue indépendante**, par un sous-agent",
      "*revue indépendante*, par un sous-agent",
      "_revue humaine_, par un relecteur",
      "Revue Indépendante par un sous-agent",
    ]) {
      assert.deepEqual(checks(evaluateReviewRecord(record({ level: "B", procedure }), files)), CLEAN, procedure);
    }
    for (const procedure of [
      "revue non indépendante, par la session auteure",
      "auto-review, sans revue indépendante, par la session auteure",
      "pas de revue humaine ; auto-review par la session auteure",
      "jamais de revue humaine, auto-review par la session auteure",
      "revue indépendante non réalisée, par la session auteure",
      "revue indépendante, non réalisée, par la session auteure",
      "revue indépendante : non, par la session auteure",
      "auto-review ; revue indépendante à prévoir, par la session auteure",
      "auto-review indépendante de rien, par la session auteure",
    ]) {
      const { problems } = evaluateReviewRecord(record({ level: "B", procedure }), files);
      assert.ok(problems.some((x) => x.includes("level B requires an independent or human review")), procedure);
    }
  });

  test("the highest level declared on the head decides; one valid record at that level is enough", () => {
    const files = { ...PR, files: ["scripts/ci/x.mjs"] };
    const pair = `${record()}\n\n${record({ level: "B", procedure: "revue indépendante, par un sous-agent" })}`;
    assert.deepEqual(checks(evaluateReviewRecord(pair, files)), CLEAN);
    const upgraded = `${record()}\n\n${record({ level: "C", procedure: "revue indépendante, par un sous-agent" })}`;
    const { problems } = evaluateReviewRecord(upgraded, { ...PR, author: "author" });
    assert.ok(problems.some((x) => x.includes("level C requires the domain owner's accord")));
  });

  describe("level C accord", () => {
    const body = record({ level: "C", procedure: "revue indépendante, par un sous-agent" });
    const ctx = { ...PR, author: "app-bot[bot]", files: ["backend/src/modules/payments/x.ts"] };
    const refused = (pr) => evaluateReviewRecord(body, pr).problems.some((x) => x.includes("level C requires the domain owner's accord"));

    test("an approval of the head by another account with write access is an accord, named in the notes", () => {
      const reviews = [{ id: 1, login: "owner", association: "OWNER", state: "APPROVED", commitId: HEAD.toUpperCase(), body: "" }];
      const r = evaluateReviewRecord(body, { ...ctx, reviews });
      assert.deepEqual(checks(r), CLEAN);
      assert.deepEqual(r.notes, ["level C accord counted from `owner` (owner, approval of the head)"]);
    });

    test("a comment line starting with « Accord » and naming the head is an accord", () => {
      for (const text of [`Accord pour la fusion de ${HEAD}.`, `- **Accord** : ${HEAD.toUpperCase()}`]) {
        const comments = [{ id: 2, login: "owner", association: "COLLABORATOR", body: `Relu.\n${text}` }];
        assert.deepEqual(checks(evaluateReviewRecord(body, { ...ctx, comments })), CLEAN, text);
      }
    });

    test("quoted, negated, withdrawn or cited text is not an accord", () => {
      for (const text of [
        `> Accord ${HEAD}`,
        `Pas d'accord sur ${HEAD}.`,
        `Accord refusé pour ${HEAD}.`,
        `Accord retiré : ${HEAD}`,
        `Accord annulé : ${HEAD}`,
        `Accord révoqué pour ${HEAD}.`,
        `Accord suspendu sur ${HEAD}`,
        `Accord, non conditionnel : ${HEAD}`,
        `La gate demande un accord sur ${HEAD}.`,
        `Accord ${HEAD}0`,
      ]) {
        const comments = [{ id: 2, login: "owner", association: "OWNER", body: text }];
        assert.ok(refused({ ...ctx, comments }), text);
      }
    });

    test("an accord withdrawn by the same account is unverified, the order not being tracked", () => {
      const approve = { id: 1, login: "owner", association: "OWNER", state: "APPROVED", commitId: HEAD, body: "" };
      const accord = { id: 2, login: "owner", association: "OWNER", body: `Accord ${HEAD}` };
      for (const text of [
        `Je retire mon accord sur ${HEAD}.`,
        `Accord retiré : ${HEAD}`,
        `- pas d'accord pour ${HEAD}`,
        `J'annule mon accord sur ${HEAD}.`,
        "Je retire mon accord.",
        `Je retire mon accord :\n${HEAD}`,
        `Accord révoqué sur ${HEAD.slice(0, 9)}`,
        `Désaccord sur ${HEAD}`,
        "Plus d'accord, voir https://github.com/o/r/pull/7#issuecomment-6556640100",
      ]) {
        const withdrawal = { id: 3, login: "owner", association: "OWNER", body: text };
        for (const pr of [{ ...ctx, reviews: [approve], comments: [withdrawal] }, { ...ctx, comments: [accord, withdrawal] }]) {
          const r = evaluateReviewRecord(body, pr);
          assert.deepEqual(r.problems, [], text);
          assert.ok(r.unverified.includes("level C accord by `owner` also withdrawn or refused by the same account, on the head or without a SHA: the order of comments is not tracked (a line about another head names its SHA)"), text);
        }
      }
      // A quoted withdrawal, or one naming another head, leaves the accord counted.
      for (const text of [`> Accord retiré : ${HEAD}`, `Accord retiré : ${OLD_HEAD}`, `Accord retiré : ${OLD_HEAD.slice(0, 9)}`]) {
        const r = evaluateReviewRecord(body, { ...ctx, comments: [accord, { id: 3, login: "owner", association: "OWNER", body: text }] });
        assert.deepEqual(checks(r), CLEAN, text);
      }
      // A negation that does not bear on the accord withdraws nothing.
      for (const text of [`Accord ${HEAD} (aucune réserve)`, `Accord ${HEAD}, pas de réserve`, "Pas besoin d'un autre accord."]) {
        const r = evaluateReviewRecord(body, { ...ctx, reviews: [approve], comments: [{ id: 3, login: "owner", association: "OWNER", body: text }] });
        assert.deepEqual(checks(r), CLEAN, text);
      }
      // The withdrawal of another account does not cancel this one.
      const other = { id: 3, login: "maintainer", association: "MEMBER", body: `Accord retiré : ${HEAD}` };
      assert.deepEqual(checks(evaluateReviewRecord(body, { ...ctx, comments: [accord, other] })), CLEAN);
    });

    test("an approval of an older head, a dismissed one, or a later change request is not", () => {
      const approve = { id: 1, login: "owner", association: "OWNER", state: "APPROVED", commitId: HEAD, body: "" };
      const older = [{ ...approve, commitId: OLD_HEAD }];
      const dismissed = [approve, { ...approve, id: 3, state: "DISMISSED" }];
      const changes = [{ ...approve, id: 3, state: "CHANGES_REQUESTED", body: `Accord ${HEAD} sous réserve` }];
      const withComment = { comments: [{ id: 2, login: "owner", association: "OWNER", body: `Accord ${HEAD}` }] };
      for (const reviews of [older, dismissed, changes]) assert.ok(refused({ ...ctx, reviews }), JSON.stringify(reviews));
      assert.ok(refused({ ...ctx, ...withComment, reviews: [approve, { ...approve, id: 4, state: "CHANGES_REQUESTED" }] }));
    });

    test("an account without write access is not counted, an unknown access is unverified", () => {
      const outsider = { ...ctx, comments: [{ id: 2, login: "someone", association: "NONE", body: `Accord ${HEAD}` }] };
      assert.ok(refused(outsider));
      const unknown = { ...ctx, comments: [{ id: 2, login: "someone", body: `Accord ${HEAD}` }] };
      assert.ok(evaluateReviewRecord(body, unknown).unverified.includes("level C accord by `someone`: repository access unknown"));
    });

    test("an accord typed by the author's account or a bot is not proof", () => {
      const own = { ...ctx, author: "owner", comments: [{ id: 2, login: "owner", association: "OWNER", body: `accord ${HEAD}` }] };
      const ownResult = evaluateReviewRecord(body, own).unverified.find((x) => x.includes("author's account only"));
      assert.ok(ownResult?.includes("(`owner`)") && !ownResult.includes("@"));
      const bot = { ...ctx, comments: [{ id: 2, login: "app-bot[bot]", association: "NONE", body: `accord ${HEAD}` }] };
      assert.ok(refused(bot));
    });

    test("without reviews or comments the accord is unverified", () => {
      const { unverified } = evaluateReviewRecord(body, { ...ctx, reviews: undefined });
      assert.ok(unverified.some((x) => x.startsWith("level C accord not checked")));
    });
  });
});

describe("evaluateReviewRecord — record in a linked comment", () => {
  const link = "Enregistrement : https://github.com/o/r/pull/7#issuecomment-42";

  test("a record in a comment the body links is read", () => {
    const comments = [{ id: 42, login: "app-bot[bot]", body: record() }];
    assert.deepEqual(checks(evaluateReviewRecord(link, { ...PR, comments })), CLEAN);
  });

  test("a record in a comment the body does not link is ignored", () => {
    const comments = [{ id: 42, login: "app-bot[bot]", body: record() }];
    const { problems } = evaluateReviewRecord("Pas de lien.", { ...PR, comments });
    assert.ok(problems[0].startsWith("no review record"));
  });

  test("a link to a comment absent from this PR fails, an unreadable one is unverified", () => {
    assert.ok(evaluateReviewRecord(link, PR).problems.includes("linked issuecomment-42 not found on this PR"));
    const { problems, unverified } = evaluateReviewRecord(link, { ...PR, comments: undefined });
    assert.deepEqual(problems, []);
    assert.ok(unverified.includes("linked issuecomment-42 not read (no review context)"));
  });

  test("a comment of another PR is not this PR's record", () => {
    const other = "https://github.com/o/r/pull/8#issuecomment-42";
    const comments = [{ id: 42, login: "x", body: record() }];
    assert.ok(evaluateReviewRecord(other, { ...PR, comments }).problems[0].startsWith("no review record"));
  });
});

describe("renderReport", () => {
  test("a report over the comment limit is cut at a line end, with a note", () => {
    const result = { pass: false, mode: "checklist", reasons: Array.from({ length: 5000 }, (_, i) => `reason ${i} ${"x".repeat(20)}`) };
    const report = renderReport(result);
    assert.ok(report.length < 61000);
    assert.ok(report.endsWith("_Report truncated at 60000 characters: the full report is in the job log._\n"));
    assert.match(report.split("\n\n_Report truncated")[0], /\n- reason \d+ x{20}$/);
    const huge = Array.from({ length: 20000 }, (_, i) => `linked issuecomment-${i} not found`).join("; ");
    const cut = renderReport({ ...result, reasons: [huge, "next"], notes: ["a note"], onProof: ["an item"] });
    assert.ok(cut.length < 61000);
    assert.match(cut, /^- linked issuecomment-0 not found; .* not found … _\(line cut\)_$/m);
    for (const kept of ["\n- next\n", "- a note", "- an item"]) assert.ok(cut.includes(kept), kept);
    const short = renderReport({ ...result, reasons: ["one"] });
    assert.ok(short.includes("- one") && !short.includes("truncated"));
  });
});

