#!/usr/bin/env node
// =============================================================================
// canon-sync PR metadata: idempotence and stale-evidence handling.
// =============================================================================
// Consumed by .github/workflows/canon-sync.yml, around
// peter-evans/create-pull-request. That action rewrites the PR body on every
// run and resets the branch as soon as the base has moved, and offers no option
// to keep an existing body. Left alone, the nightly cron would erase recorded
// evidence and replace a reviewed head even when the mirrors did not change.
//
// `prepare` (before the action, read-only on GitHub):
//   - open PR whose head already carries the synced content => skip the action:
//     no push, no body edit, the reviewed head and its evidence stay valid;
//   - otherwise render the body the action will write. Evidence recorded for the
//     outgoing head moves to a stale archive: kept in full, named as stale, and
//     blockquoted so pr-dod-gate.mjs cannot read it as a checklist.
//     No box is ever ticked here.
// `verify` (after the action): the announced operation happened, the new head is
// verified by GitHub and the PR carries its assignee.
//
// Every read failure, ambiguous PR state or malformed body stops the job before
// anything is written.
//
// Env: GITHUB_REPOSITORY, GITHUB_REF_NAME, RUNNER_TEMP, GITHUB_OUTPUT, GH_TOKEN,
//      EVENT_NAME, EVENT_ACTION, RUN_URL (prepare);
//      EXPECTED_OPERATIONS, PREVIOUS_HEAD, CPR_OPERATION, CPR_HEAD_SHA,
//      CPR_VERIFIED, CPR_NUMBER, CANON_SYNC_ASSIGNEE (verify).
// =============================================================================

import { execFileSync } from "node:child_process";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

export const BRANCH = "canon-sync/auto";
export const MAX_BODY_CHARS = 65536;
export const PR_TEMPLATE_PATH = ".github/PULL_REQUEST_TEMPLATE.md";
const DOD_COUNT = 9;
const PAGE_SIZE = 100;
const WRITING_OPERATIONS = ["created", "updated"];

const SECTIONS = ["generated", "review", "archive"];
const marker = (section, edge) => `<!-- canon-sync:${section}:${edge} -->`;
const MARKERS = SECTIONS.flatMap((s) => [marker(s, "start"), marker(s, "end")]);
const ARCHIVE_HEADING = "## Stale evidence (not valid for the current head)";

export const GENERATED_TEXT = `Auto-generated by \`.github/workflows/canon-sync.yml\`.

The script \`scripts/ci/sync-canon-from-vault.sh\` reads
\`99-meta/canon-hashes.json\` from \`ak125/governance-vault@main\`,
applies the canonical strip-frontmatter transform to each canon
file, and writes the bytes to every declared mirror in this repo.

**Verification :**
- The sync script is fail-closed: it aborts before touching any
  mirror file if the produced sha256 does not match
  \`distribution_sha256\`.
- On merge, the per-canon \`*-hash.yml\` workflows re-verify the
  bytes against the vault (defense-in-depth).

**No manual edit needed** in the mirrors. Merging stays a human decision.`;

const TRIGGER_LINE = /\n*Trigger: .*$/;

/** The nine unticked DoD lines of the repository PR template. */
export function extractDodLines(template) {
  const lines = template.split(/\r?\n/).filter((line) => /^- \[ \] DoD\d\b/.test(line));
  if (lines.length !== DOD_COUNT) {
    throw new Error(`${PR_TEMPLATE_PATH}: expected ${DOD_COUNT} unticked DoD lines, found ${lines.length}`);
  }
  return lines;
}

export function reviewPlaceholder(dodLines) {
  return [
    "## Review evidence for the current head",
    "",
    "None recorded yet. Evidence must name the exact head SHA (ADR-120 D2/D4).",
    "A head change moves this section to the stale archive below.",
    "",
    ...dodLines,
  ].join("\n");
}

/**
 * Splits a PR body into its sections. A body without markers is legacy: all of
 * it counts as evidence to preserve. Partial or reordered markers are an error.
 */
export function parseBody(body) {
  const text = (body ?? "").replace(/\r\n/g, "\n").trim();
  const empty = { generated: "", review: "", archive: "", outside: "" };
  if (text === "") return empty;

  const lines = text.split("\n");
  const found = lines.flatMap((line, index) => (MARKERS.includes(line.trim()) ? [{ index, line: line.trim() }] : []));
  if (found.length === 0) return { ...empty, outside: text };
  if (found.length !== MARKERS.length || found.some((hit, i) => hit.line !== MARKERS[i])) {
    throw new Error("canon-sync PR body has missing, duplicated or reordered markers; fix the body by hand");
  }

  const between = (from, to) => lines.slice(from, to).join("\n").trim();
  const [gs, ge, rs, re, as, ae] = found.map((hit) => hit.index);
  const outside = [...lines.slice(0, gs), ...lines.slice(ge + 1, rs), ...lines.slice(re + 1, as), ...lines.slice(ae + 1)]
    .filter((line) => line.trim() !== ARCHIVE_HEADING)
    .join("\n")
    .trim();
  return { generated: between(gs + 1, ge), review: between(rs + 1, re), archive: between(as + 1, ae), outside };
}

function fenceFor(content) {
  const longest = Math.max(0, ...(content.match(/`+/g) ?? []).map((run) => run.length));
  return "`".repeat(Math.max(3, longest + 1));
}

/** Blockquoted and fenced: readable, inert for the DoD gate, no live checkbox. */
export function archiveEntry({ content, headSha, replacedAt, runUrl }) {
  const fence = fenceFor(content);
  return [
    `Evidence recorded for head \`${headSha}\`, replaced on ${replacedAt} by ${runUrl}. It does not apply to the current head.`,
    "",
    `${fence}text`,
    ...content.split("\n"),
    fence,
  ]
    .map((line) => (line === "" ? ">" : `> ${line}`))
    .join("\n");
}

/** Everything a person or agent wrote for the outgoing head, empty if nothing. */
function collectEvidence(previous, dodLines) {
  const parts = [];
  if (previous.generated && previous.generated.replace(TRIGGER_LINE, "") !== GENERATED_TEXT) {
    parts.push(previous.generated);
  }
  if (previous.review && previous.review !== reviewPlaceholder(dodLines)) parts.push(previous.review);
  if (previous.outside) parts.push(previous.outside);
  return parts.join("\n\n");
}

export function renderBody({ previousBody, previousHead, trigger, dodLines, replacedAt, runUrl }) {
  const previous = parseBody(previousBody);
  const evidence = collectEvidence(previous, dodLines);
  if (evidence && !previousHead) throw new Error("existing evidence without a known head SHA");

  const entry = evidence ? archiveEntry({ content: evidence, headSha: previousHead, replacedAt, runUrl }) : "";
  const archive = [entry, previous.archive].filter(Boolean).join("\n\n");
  const body = [
    marker("generated", "start"),
    GENERATED_TEXT,
    "",
    `Trigger: ${trigger}`,
    marker("generated", "end"),
    "",
    marker("review", "start"),
    reviewPlaceholder(dodLines),
    marker("review", "end"),
    "",
    ...(archive ? [ARCHIVE_HEADING, ""] : []),
    marker("archive", "start"),
    ...(archive ? [archive] : []),
    marker("archive", "end"),
    "",
  ].join("\n");

  if (body.length > MAX_BODY_CHARS) {
    throw new Error(`rendered PR body is ${body.length} chars (limit ${MAX_BODY_CHARS}); trim the stale archive by hand`);
  }
  return body;
}

/** Skip only when an open PR already carries exactly what the sync produced. */
export function decide({ hasOpenPr, syncChanged, differing }) {
  const hasSync = syncChanged.length > 0;
  if (hasOpenPr && hasSync && differing.length === 0) return { skip: true, expected: [] };
  if (hasOpenPr) return { skip: false, expected: [hasSync ? "updated" : "closed"] };
  return { skip: false, expected: hasSync ? ["created"] : ["none", "closed"] };
}

function required(env, name) {
  const value = env[name];
  if (!value) throw new Error(`missing environment variable ${name}`);
  return value;
}

function findOpenPr(ghJson, repo, baseRef) {
  const owner = repo.split("/")[0];
  const open = ghJson(`repos/${repo}/pulls?state=open&head=${owner}:${BRANCH}&base=${encodeURIComponent(baseRef)}&per_page=${PAGE_SIZE}`);
  if (open.length > 1) throw new Error(`${open.length} open PRs for ${BRANCH}; expected at most one`);
  return open.length === 1 ? ghJson(`repos/${repo}/pulls/${open[0].number}`) : null;
}

function listPrPaths(ghJson, repo, pr) {
  const files = [];
  for (let page = 1; ; page += 1) {
    const batch = ghJson(`repos/${repo}/pulls/${pr.number}/files?per_page=${PAGE_SIZE}&page=${page}`);
    files.push(...batch);
    if (batch.length < PAGE_SIZE) break;
  }
  if (files.length !== pr.changed_files) {
    throw new Error(`PR #${pr.number}: listed ${files.length} files, GitHub reports ${pr.changed_files}`);
  }
  return files.flatMap((file) => (file.previous_filename ? [file.filename, file.previous_filename] : [file.filename]));
}

function remoteBlob(ghApi, repo, ref, path) {
  const encoded = path.split("/").map(encodeURIComponent).join("/");
  const raw = ghApi(`repos/${repo}/contents/${encoded}?ref=${ref}`, { allowNotFound: true });
  if (raw === null) return null;
  const entry = JSON.parse(raw);
  if (Array.isArray(entry) || entry.type !== "file") throw new Error(`${path}: not a regular file on ${ref}`);
  return entry.sha;
}

function warningsFor(pr, verified) {
  const warnings = [];
  if ((pr.assignees ?? []).length === 0) warnings.push(`PR #${pr.number} has no assignee.`);
  if (!verified) warnings.push(`PR #${pr.number} head ${pr.head.sha} is not verified by GitHub.`);
  return warnings;
}

export function prepare({ ghApi, listChanged, localBlob, env, now, dodLines, writeBody }) {
  const ghJson = (path) => JSON.parse(ghApi(path));
  const repo = required(env, "GITHUB_REPOSITORY");
  const baseRef = required(env, "GITHUB_REF_NAME");
  const bodyPath = join(required(env, "RUNNER_TEMP"), "canon-sync-pr-body.md");

  const pr = findOpenPr(ghJson, repo, baseRef);
  const syncChanged = listChanged();
  let differing = [];
  if (pr) {
    const paths = [...new Set([...listPrPaths(ghJson, repo, pr), ...syncChanged])].sort();
    differing = paths.filter((path) => localBlob(path) !== remoteBlob(ghApi, repo, pr.head.sha, path));
  }

  const { skip, expected } = decide({ hasOpenPr: Boolean(pr), syncChanged, differing });
  const outputs = { skip: String(skip), previous_head: pr?.head.sha ?? "", expected: expected.join(",") };
  if (skip) {
    const verified = ghJson(`repos/${repo}/commits/${pr.head.sha}`).commit.verification.verified === true;
    return { outputs, warnings: warningsFor(pr, verified), pr };
  }

  const action = env.EVENT_ACTION ? ` (${env.EVENT_ACTION})` : "";
  writeBody(
    bodyPath,
    renderBody({
      // Without synced changes the action only closes the PR and ignores the body.
      previousBody: syncChanged.length > 0 ? pr?.body : "",
      previousHead: pr?.head.sha,
      trigger: `${required(env, "EVENT_NAME")}${action}`,
      dodLines,
      replacedAt: now(),
      runUrl: required(env, "RUN_URL"),
    }),
  );
  return { outputs: { ...outputs, body_path: bodyPath }, warnings: [], pr };
}

export function verify({ ghApi, env }) {
  const operation = env.CPR_OPERATION ?? "";
  const expected = required(env, "EXPECTED_OPERATIONS").split(",");
  if (!expected.includes(operation)) {
    throw new Error(`action reported operation '${operation}', expected ${expected.join(" or ")}`);
  }
  if (!WRITING_OPERATIONS.includes(operation)) return { checked: false };

  const repo = required(env, "GITHUB_REPOSITORY");
  const assignee = required(env, "CANON_SYNC_ASSIGNEE");
  const head = required(env, "CPR_HEAD_SHA");
  const number = required(env, "CPR_NUMBER");
  if (head === env.PREVIOUS_HEAD) throw new Error(`head ${head} did not change`);
  if (env.CPR_VERIFIED !== "true") throw new Error(`head ${head} is not verified by GitHub`);

  const pr = JSON.parse(ghApi(`repos/${repo}/pulls/${number}`));
  if (pr.head.sha !== head) throw new Error(`PR #${number} head is ${pr.head.sha}, action reported ${head}`);
  if (!(pr.assignees ?? []).some((user) => user.login === assignee)) {
    throw new Error(`PR #${number} is not assigned to ${assignee}`);
  }
  return { checked: true };
}

export function createGhApi(token) {
  return (path, { allowNotFound = false } = {}) => {
    try {
      return execFileSync("gh", ["api", path], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "pipe"],
        env: { ...process.env, GH_TOKEN: token },
      });
    } catch (error) {
      if (allowNotFound && String(error.stderr ?? "").includes("HTTP 404")) return null;
      throw new Error(`gh api ${path} failed: ${String(error.stderr ?? error.message).trim()}`);
    }
  };
}

export function createGitReader(cwd) {
  const git = (args) => execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
  return {
    listChanged: () =>
      git(["status", "--porcelain=v1", "-z", "--no-renames", "--untracked-files=all"])
        .split("\0")
        .filter(Boolean)
        .map((entry) => entry.slice(3))
        .sort(),
    localBlob: (path) => (existsSync(join(cwd, path)) ? git(["hash-object", "--", path]).trim() : null),
  };
}

function main() {
  const command = process.argv[2];
  const env = process.env;
  const ghApi = createGhApi(required(env, "GH_TOKEN"));
  if (command === "verify") {
    verify({ ghApi, env });
    console.log("canon-sync: post-conditions verified");
    return;
  }
  if (command !== "prepare") throw new Error(`unknown command '${command ?? ""}'`);

  const cwd = process.cwd();
  const { outputs, warnings, pr } = prepare({
    ghApi,
    ...createGitReader(cwd),
    env,
    now: () => new Date().toISOString(),
    dodLines: extractDodLines(readFileSync(join(cwd, PR_TEMPLATE_PATH), "utf8")),
    writeBody: (path, body) => writeFileSync(path, body, "utf8"),
  });
  for (const warning of warnings) console.log(`::warning::${warning}`);
  if (outputs.skip === "true") {
    console.log(`::notice::PR #${pr.number} already carries the synced mirrors: head and body left untouched.`);
  }
  const lines = Object.entries(outputs).map(([key, value]) => `${key}=${value}`);
  appendFileSync(required(env, "GITHUB_OUTPUT"), `${lines.join("\n")}\n`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    console.error(`::error::canon-sync: ${error.message}`);
    process.exit(1);
  }
}
